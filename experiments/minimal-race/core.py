class World:
    def __init__(self, seed, config=None):
        conf = config or make_base_config()
        self.conf = conf
        self.cfg = conf["cfg"]
        self.mech = dict(BASE_CONFIG["mech"], **self.cfg.get("mech", {}))
        self.templates = conf["templates"]
        self.roles = conf["roles"]
        self.govs_conf = conf["govs"]
        self.seed = seed
        self.t = 0
        self.unk = {k: lo + (hi - lo) * self.u("unk", k)
                    for k, (lo, hi) in self.cfg["unknowns"].items()}
        self.labs = {}
        for name, r in self.roles.items():
            self.labs[name] = Lab(name=name, role=name, bloc=r["bloc"], cash=r["cash"],
                                  K=r["compute"], C=r["C"], S=r["S"], ext=r["ext"])
            self.labs[name].deployed_C = r["C"] * 0.9
        start_C = {n: l.deployed_C for n, l in self.labs.items()}
        rwm = self.mech["role_world_models"]
        dflt = self.cfg["default_rival_safety"]
        self.beliefs = {}
        for name, r in self.roles.items():
            self.beliefs[name] = Beliefs(
                name, list(self.labs), self.cfg, r["hazard_prior"], r["demand_prior"],
                r["receptivity"], r["attention"], start_C,
                r["rival_safety"] if rwm else dflt,
                r["self_discount"] if self.mech["motivated"] else 0.0)
        for b, g in self.govs_conf.items():
            self.beliefs[f"gov{b}"] = Beliefs(
                f"gov{b}", list(self.labs), self.cfg, g["hazard_prior"], 0.5,
                g["receptivity"], g["attention"], start_C,
                g["rival_safety"] if rwm else dflt)
        self.public = {b: 0.0 for b in self.govs_conf}
        self.sentiment = self.cfg["sentiment0"]
        self.chip_price = self.cfg["chip_price0"]
        self.gov_policy = {b: {"subsidy": 0.0, "regulate": 0.0, "disclosure": False,
                               "consolidated": False, "cooldown": 0}
                           for b in self.govs_conf}
        self.hostility = {b: 0.0 for b in self.govs_conf}
        self.gap_hist = {b: [] for b in self.govs_conf}
        self.export_controls = False
        self.pact = None            # dict(members=set, start=t, verify=float, kind=str)
        self.signals = []           # all signals ever generated (observed by someone)
        self.bench_hist = {n: [] for n in self.labs}   # public benchmark history
        self._new_signals = []
        self.events = []            # log of notable events (truth)
        self.history = []           # per-quarter snapshot dicts
        self.outcome = None
        self.expected_rev_growth = 0.05
        self.last_market_rev = 0.0
        self.market_rev = 0.0
        self.pending_incidents = []

    # ---------------- keyed randomness ----------------
    def u(self, *key):
        """Uniform(0,1) determined only by (seed, key). Use a key naming the
        purpose, quarter and actor, e.g. self.u("incident", self.t, lab.name)."""
        h = hashlib.blake2b(repr((self.seed,) + key).encode(), digest_size=8).digest()
        return ((int.from_bytes(h, "big") >> 11) + 0.5) / 2.0 ** 53

    def gauss(self, sd, *key):
        u1 = self.u(*key, "g1")
        u2 = self.u(*key, "g2")
        return sd * math.sqrt(-2.0 * math.log(u1)) * math.cos(2 * math.pi * u2)

    def expo(self, *key):
        return -math.log(1.0 - self.u(*key) + 1e-300)

    # ---------------- helpers ----------------
    def live_labs(self):
        return [l for l in self.labs.values() if l.alive]

    def log(self, kind, **kw):
        self.events.append(dict(t=self.t, kind=kind, **kw))

    def adoption(self, t=None):
        """Share of eventual demand adopted by quarter t. The hidden midpoint
        is world truth; actors only see the resulting revenue."""
        c = self.cfg
        t = self.t if t is None else t
        mid = self.unk.get("adoption_mid", c["adoption_mid"])
        return 1.0 / (1.0 + math.exp(-c["adoption_rate"] * (t - mid)))

    def public_adoption(self, t):
        """The public's view of adoption: the scenario's default curve, not
        the hidden midpoint."""
        c = self.cfg
        return 1.0 / (1.0 + math.exp(-c["adoption_rate"] * (t - c["adoption_mid"])))

    def frontier_deployed(self):
        return max((l.deployed_C for l in self.live_labs()), default=0.0)

    def hz_frac(self, who):
        return self.beliefs[who].hazard.mean() / self.cfg["unknowns"]["hazard"][1]

    def believed_bloc_best(self, who, bloc, proj=0):
        B = self.beliefs[who]
        vals = [B.cap[l.name].mu + proj * B.cap[l.name].growth
                for l in self.live_labs() if l.bloc == bloc and l.name in B.cap]
        if who in self.labs and self.labs[who].bloc == bloc and self.labs[who].alive:
            vals.append(self.labs[who].C)
        return max(vals, default=0.0)

    # ---------------- the quarter ----------------
    def step(self):
        self.arrive_compute()
        self.observe()
        self.internalize()
        self.government_decide()
        self.covert_ops()
        self.diplomacy()
        self.labs_decide()
        self.compute_market()
        self.capital_market()
        self.resolve_rnd()
        self.product_market()
        self.incidents()
        self.public_opinion()
        self.accounting()
        self.check_end()
        self.snapshot()
        self.t += 1

    def run(self):
        while self.t < self.cfg["T"] and self.outcome is None:
            self.step()
        if self.outcome is None:
            self.outcome = dict(kind="no_takeoff", t=self.t, winner=None, bloc=None)
        return self

    # ---- 1. compute arrives
    def arrive_compute(self):
        for l in self.live_labs():
            keep = []
            for (ta, units) in l.pipeline:
                if ta <= self.t:
                    l.K += units
                else:
                    keep.append((ta, units))
            l.pipeline = keep

    # ---- 2. observation layer: truth -> signals
    def observe(self):
        c = self.cfg
        self._new_signals = []
        if self.t == 0:
            return
        new = []
        for l in self.live_labs():
            y = l.deployed_C + self.gauss(c["bench_noise"], "bench", self.t, l.name)
            new.append(Signal(self.t, "bench", l.name, y))
            self.bench_hist[l.name].append((self.t, y))
            if l.capex > 0 and self.u("see_build", self.t, l.name) < 0.8:
                new.append(Signal(self.t, "build", l.name, l.capex))
            p_seen = c["train_detect"]
            if self.pact and l.name in self.pact["members"]:
                p_seen = max(p_seen, self.pact["verify"])
            if self.u("see_train", self.t, l.name) < p_seen:
                new.append(Signal(self.t, "train", l.name, l.train_frac))
            new.append(Signal(self.t, "revenue", l.name, l.revenue))
        for inc in self.pending_incidents:
            new.append(Signal(self.t, "incident", inc["lab"], inc["sev"], public=inc["public"],
                              observers=() if inc["public"] else (inc["lab"],)))
        self.pending_incidents = []
        self.signals.extend(new)
        self._new_signals = new

    # ---- 3. internalization layer: signals -> beliefs
    def internalize(self):
        if self.t == 0:
            return
        c = self.cfg
        new = self._new_signals
        nv = c["bench_noise"] ** 2
        for who, B in self.beliefs.items():
            for est in B.cap.values():
                est.predict()
            n_own, n_other = 0, 0
            for s in new:
                if not s.public and who not in s.observers:
                    continue
                if s.kind == "bench" and s.subject in B.cap:
                    my_bloc = self.labs[who].bloc if who in self.labs else who[-1]
                    trust = 1.6 if self.labs[s.subject].bloc != my_bloc else 1.0
                    B.cap[s.subject].observe(s.value, nv * trust, B.attention)
                elif s.kind == "train" and s.subject in B.cap:
                    B.cap[s.subject].growth += 0.6 * s.value
                    if self.pact and s.subject in self.pact["members"]:
                        if s.value > c["pact_cap"] + 1e-9:
                            B.defect_a += 1.0
                        else:
                            B.defect_b += 0.5     # observed compliance builds trust
                elif s.kind == "incident":
                    if s.subject == who:
                        n_own += 1
                    else:
                        n_other += 1
            B.incidents_seen += n_own + n_other
            # Motivated reasoning: a lab explains away part of its own incidents.
            n_eff = n_other + (1.0 - B.self_discount) * n_own
            # Expected observed incidents: a lab sees all of its own, but only
            # the publicised share of everyone else's. Actors do not know the
            # true publicity rate; they assume a believed rate of 0.6.
            e_own, e_other = self.believed_exposure(who, split=True)
            def ll(h, n=n_eff, eo=e_own, ex=e_other, d=self.believed_detect):
                lam = max(1e-6, h * (eo + d * ex))
                return n * math.log(lam) - lam
            B.hazard.update(ll, B.receptivity)
            obs_rev = sum(s.value for s in new if s.kind == "revenue")
            benches = [s.value for s in new if s.kind == "bench"]
            front_pub = max(benches, default=0.0)
            pot = c["market0"] * self.public_adoption(self.t - 1) * (max(0.0, front_pub) / 10.0) ** 1.3
            if pot > 0.05:
                def lld(d, r=obs_rev, p=pot):
                    pred = d * p
                    return -((r - pred) ** 2) / (2 * (0.3 * pred + 0.2) ** 2)
                B.demand.update(lld, B.receptivity * 0.5)

    believed_detect = 0.6
    assumed_exposure = 0.55   # assumed (0.3*train share + serve share) for rivals

    def believed_exposure(self, who, split=False):
        """Exposure as the actor understands it. Labs know their own gap; for
        everyone else the actor applies its own model of the world: rivals'
        safety is assumed to be `rival_safety` times believed capability."""
        B = self.beliefs[who]
        e_own, e_other = 0.0, 0.0
        for l in self.live_labs():
            if l.name == who:
                factor = 0.3 * l.train_frac + l._serve_share
                e_own += max(0.0, l.C - l.S) / 10.0 * factor
            elif l.name in B.cap:
                e_other += max(0.0, B.cap[l.name].mu * (1 - B.rival_safety)) / 10.0 * self.assumed_exposure
        return (e_own, e_other) if split else e_own + e_other

    # ---- 4. governments: industrial policy, regulation, disclosure, consolidation
    def government_decide(self):
        for b, g in self.govs_conf.items():
            who = f"gov{b}"
            other = [x for x in self.govs_conf if x != b][0]
            own = self.believed_bloc_best(who, b)
            oth = self.believed_bloc_best(who, other)
            gap = own - oth                     # positive = ahead
            self.gap_hist[b].append(gap)
            hz = self.hz_frac(who)
            pub = self.public[b]
            w = g["w"]
            s_subsidy = w["nation"] * max(0.0, 2.0 - gap) / 2.0
            s_regulate = w["public"] * pub + w["safety"] * hz * 2.0
            pol = self.gov_policy[b]
            prev = dict(pol)
            pol["subsidy"] = max(0.0, min(1.0, s_subsidy - 0.5 * s_regulate))
            pol["regulate"] = max(0.0, min(1.0, s_regulate - 0.6))
            if pol["regulate"] > 0.05 and prev["regulate"] <= 0.05:
                self.log("regulate_on", gov=b, level=round(pol["regulate"], 3))
            if pol["regulate"] <= 0.05 < prev["regulate"]:
                self.log("regulate_off", gov=b)
            if pol["subsidy"] > 0.05 and prev["subsidy"] <= 0.05:
                self.log("subsidy_on", gov=b, level=round(pol["subsidy"], 3))
            hist = self.gap_hist[b]
            closing = len(hist) >= 5 and gap < hist[-5] - 0.75
            if b == "A" and not self.export_controls and w["nation"] > 0.5 and (closing or 0 < gap < 1.0):
                self.export_controls = True
                self.log("export_controls", gov=b, trigger="closing" if closing else "near_parity")
            # Mandatory disclosure: a sticky law passed under public pressure or fear.
            if self.mech["disclosure"] and not pol["disclosure"]:
                if pub > 0.6 * w["public"] + 0.4 or hz > 0.55:
                    pol["disclosure"] = True
                    self.log("disclosure_on", gov=b)
            if self.mech["consolidation"] and not pol["consolidated"]:
                self.maybe_consolidate(b, g)

    def maybe_consolidate(self, b, g):
        """Merge domestic labs into a national project when the government
        believes its bloc is far behind AND falling further behind."""
        hist = self.gap_hist[b]
        if len(hist) < 5:
            return
        domestic = [l for l in self.live_labs() if l.bloc == b]
        if len(domestic) < 2:
            return
        falling = hist[-1] < hist[-5] - 0.5
        if hist[-1] < g["consolidate_gap"] and falling:
            B = self.beliefs[f"gov{b}"]
            into = max(domestic, key=lambda l: B.cap[l.name].mu)
            absorbed = []
            for l in domestic:
                if l is into:
                    continue
                into.K += l.K
                into.cash += max(0.0, l.cash)
                into.C = max(into.C, l.C)
                into.S = max(into.S, l.S)
                into.pipeline.extend(l.pipeline)
                l.alive = False
                absorbed.append(l.name)
            self.gov_policy[b]["consolidated"] = True
            self.log("consolidate", gov=b, into=into.name, absorbed=absorbed)

    # ---- 5. covert operations: theft and sabotage (belief-triggered)
    def covert_ops(self):
        c = self.cfg
        for b, g in self.govs_conf.items():
            who = f"gov{b}"
            other = [x for x in self.govs_conf if x != b][0]
            B = self.beliefs[who]
            pol = self.gov_policy[b]
            if pol["cooldown"] > 0:
                pol["cooldown"] -= 1
                continue
            targets = [l for l in self.live_labs() if l.bloc == other and l.name in B.cap]
            mine = [l for l in self.live_labs() if l.bloc == b and l.name in B.cap]
            if not targets or not mine:
                continue
            tgt = max(targets, key=lambda l: B.cap[l.name].mu)
            gap = self.believed_bloc_best(who, b) - self.believed_bloc_best(who, other)
            # Theft: tried when believed behind.
            if self.mech["theft"] and gap < -c["theft_gap"]:
                if self.u("theft_try", self.t, b) < c["theft_try"] * g["aggression"]:
                    thief = max(mine, key=lambda l: B.cap[l.name].mu)
                    self.log("theft_attempt", gov=b, target=tgt.name, thief=thief.name)
                    pol["cooldown"] = 1
                    p_ok = 0.5 * (1 - min(0.8, tgt.S / max(1e-6, tgt.C)))
                    if self.u("theft_ok", self.t, b) < p_ok:
                        new_c = thief.C + 0.5 * max(0.0, 0.9 * tgt.C - thief.C)
                        gain = new_c - thief.C
                        thief.C = new_c
                        if gain > 0:
                            self.log("theft_success", gov=b, target=tgt.name, thief=thief.name,
                                     gain=round(gain, 3))
                    if self.u("theft_seen", self.t, b) < c["theft_detect"]:
                        self.hostility[other] += 1.0
                        self.log("theft_detected", gov=other, target=tgt.name)
                        if other == "A" and not self.export_controls:
                            self.export_controls = True
                            self.log("export_controls", gov="A")
                    continue
            # Sabotage: tried when the rival bloc is believed close to takeoff
            # and ahead; hostility from detected attacks makes it likelier.
            if self.mech["sabotage"]:
                reach = self.believed_bloc_best(who, other, proj=self.cfg["horizon"])
                near = reach >= c["sabotage_reach"] * c["C_STAR"]
                if near and gap < -1.0:
                    p = c["sabotage_try"] * g["aggression"] * (1 + 0.5 * self.hostility[b])
                    if self.u("sabotage_try", self.t, b) < min(0.9, p):
                        lost = tgt.K * c["sabotage_damage"]
                        tgt.K -= lost
                        pol["cooldown"] = 2
                        self.log("sabotage", gov=b, target=tgt.name, lost=round(lost, 3))
                        if self.u("sabotage_seen", self.t, b) < c["sabotage_detect"]:
                            self.hostility[other] += 1.0
                            self.log("sabotage_detected", gov=other, target=tgt.name)

    # ---- 6. diplomacy: lab pact formation, maintenance, expiry
    def prune_pact(self):
        """Drop dead labs from a pact; end it if too few members remain."""
        if not self.pact:
            return
        dead = {n for n in self.pact["members"] if not self.labs[n].alive}
        if dead:
            for n in dead:
                self.labs[n].in_pact = False
            self.pact["members"] -= dead
            if len(self.pact["members"]) < self.cfg["pact_min"]:
                self.log("pact_expire", members=sorted(self.pact["members"]), reason="members_lost")
                self.end_pact()

    def diplomacy(self):
        c = self.cfg
        self.prune_pact()
        if self.pact:
            caught = [s.subject for s in self._new_signals
                      if s.kind == "train" and s.subject in self.pact["members"]
                      and s.value > c["pact_cap"] + 1e-9]
            if caught:
                # Beliefs already updated in internalize(); do not count twice.
                self.log("pact_break", members=sorted(self.pact["members"]),
                         violators=sorted(set(caught)))
                self.end_pact()
                return
            if self.t - self.pact["start"] >= c["pact_len"]:
                self.log("pact_expire", members=sorted(self.pact["members"]))
                self.end_pact()
            return
        labs = self.live_labs()
        if not labs:
            return
        hz_lo, hz_hi = self.cfg["unknowns"]["hazard"]
        rise = lambda n: (self.beliefs[n].hazard.mean() - self.beliefs[n].hazard_prior_mean) / (hz_hi - hz_lo)
        worried = max(labs, key=lambda l: rise(l.name))
        if rise(worried.name) < 0.05:
            return
        joiners = {l.name for l in labs}   # proposal: "if everyone joined, would you?"
        for _ in range(3):
            nxt = set()
            for l in labs:
                if self.join_value(l, joiners) > 0:
                    nxt.add(l.name)
            joiners = nxt
        if len(joiners) >= c["pact_min"]:
            self.pact = dict(members=joiners, start=self.t, verify=c["pact_verify"], kind="lab")
            for n in joiners:
                self.labs[n].in_pact = True
            self.log("pact_form", members=sorted(joiners), proposer=worried.name)

    def join_value(self, lab, expected_joiners):
        """Benefit of joining: lower hazard exposure. Cost: lost lead if you
        are (believed) ahead; laggards lose less. Conditional on others."""
        B = self.beliefs[lab.name]
        w = self.roles[lab.role]["w"]
        hz = self.hz_frac(lab.name)
        rivals = [B.cap[l.name].mu for l in self.live_labs() if l.name in B.cap]
        lead = lab.C - max(rivals) if rivals else 0.0
        others = len(expected_joiners - {lab.name})
        coverage = others / max(1, len(self.live_labs()) - 1)
        benefit = w["safety"] * hz * 3.0 * coverage
        cost = w["lead"] * (0.5 + max(0.0, lead) * 0.4) + w["nation"] * 0.3
        trust = 1.0 - B.p_defect()
        return benefit * trust - cost * 0.6 + 0.2 * coverage

    def end_pact(self):
        if self.pact:
            for n in self.pact["members"]:
                if n in self.labs:
                    self.labs[n].in_pact = False
        self.pact = None

    # ---- 7. lab decisions
    def labs_decide(self):
        for l in self.live_labs():
            scores = {name: self.score_template(l, name, tpl)
                      for name, tpl in self.templates.items()}
            allowed = dict(scores)
            if l.in_pact and self.pact:
                compliant = {k: v for k, v in scores.items()
                             if self.templates[k][1] <= self.cfg["pact_cap"] + 1e-9}
                if compliant:
                    best_c = max(compliant.values())
                    best_all = max(scores.values())
                    penalty = 1.5 + self.roles[l.role]["w"]["safety"]
                    if best_all - best_c <= self.pact["verify"] * penalty:
                        allowed = compliant
            choice = self.softmax_pick(allowed, l.template, l.name)
            if l.in_pact and self.templates[choice][1] > self.cfg["pact_cap"] + 1e-9:
                self.log("defect", lab=l.name, template=choice)
            if choice != l.template:
                self.log("switch", lab=l.name, frm=l.template, to=choice)
            l.template = choice
            self.maybe_open_weights(l)

    def score_template(self, lab, name, tpl):
        c = self.cfg
        B = self.beliefs[lab.name]
        w = self.roles[lab.role]["w"]
        build, train, safety, serve = tpl
        tot = train + safety + serve
        H = c["horizon"]
        reg = self.gov_policy[lab.bloc]["regulate"]
        tK = lab.K * train / tot * (1 - 0.5 * reg)
        sK = lab.K * safety / tot
        vK = lab.K * serve / tot
        lag = c["compute_lag"]
        build_spend = 0.5 * build * max(0.0, lab.cash)          # as in compute_market
        new_units = build_spend / max(1e-6, self.chip_price)
        live_q = max(0, H - lag)                                # quarters new compute is usable
        # Depreciation: average share of today's compute still installed over
        # the horizon, and of new compute over the quarters it is usable.
        keep = 1.0 - self.depreciation_rate()
        held = sum(keep ** h for h in range(H)) / H
        fresh = sum(keep ** h for h in range(live_q)) / live_q if live_q else 1.0
        tK = tK * held
        sK = sK * held
        vK = vK * held
        tK_new = new_units * fresh * train / tot * (1 - 0.5 * reg)
        gain = self.train_gain(lab, tK, believed=True) * H
        gain += (self.train_gain(lab, tK + tK_new, believed=True)
                 - self.train_gain(lab, tK, believed=True)) * live_q
        C_h = lab.C + gain
        S_h = lab.S + c["safety_k"] * math.sqrt(max(0.0, sK)) * H
        rivals_est = [B.cap[l.name] for l in self.live_labs() if l.name in B.cap]
        rivals = [e.mu + e.growth * H for e in rivals_est]
        top = max(rivals) if rivals else 0.0
        sd = math.sqrt(sum(e.var for e in rivals_est) / max(1, len(rivals_est)) + 1.0)
        p_lead = 0.5 * (1 + math.erf((C_h - top) / (sd * math.sqrt(2))))
        prize = 1.0 + 2.0 * max(0.0, (C_h / c["C_STAR"]) - 0.5)
        dem = B.demand.mean()
        mkt = c["market0"] * dem * (max(C_h, top) / 10.0) ** 1.3 * self.adoption()
        share = vK / (vK + sum(max(0.5, r / 3) for r in rivals))
        rev = min(mkt * share, vK * c["serve_cap"]) * H
        spend = build_spend + c["upkeep"] * (lab.K * H * held + new_units * live_q * fresh)
        # Funding outlook: investors reward visible growth, scaled by the
        # current (public) sentiment already embedded in recent raises.
        raise_h = 0.0
        if self.mech["funding_in_decisions"]:
            growth_q = gain / H
            raise_h = lab.raised_ema * math.exp(0.4 * (min(3.0, growth_q) - 0.5)) * H
        cash_h = lab.cash + rev + raise_h - spend
        broke = 3.0 if cash_h < 0 else 0.0
        hz = B.hazard.mean()
        gap = max(0.0, C_h - S_h)
        risk = hz * gap / 10.0 * (1 + 2 * max(0.0, C_h / c["C_STAR"] - 0.6))
        u = (w["lead"] * p_lead * prize
             + w["profit"] * (rev + raise_h - spend) / 10.0
             + w["nation"] * p_lead * 0.5
             - w["safety"] * risk * 2.0
             - broke
             + 0.15 * math.sqrt(new_units * keep ** live_q))   # compute outlasts the horizon
        return u

    def depreciation_rate(self):
        return self.cfg["depreciation"] if self.mech["depreciation"] else 0.0

    def softmax_pick(self, scores, current, who):
        T = self.cfg["softmax_temp"]
        items = sorted(scores.items())
        vals = [v + (self.cfg["inertia"] if k == current else 0.0) for k, v in items]
        m = max(vals)
        ws = [math.exp((v - m) / max(1e-6, T)) for v in vals]
        r = self.u("decide", self.t, who) * sum(ws)
        for (k, _), wgt in zip(items, ws):
            r -= wgt
            if r <= 0:
                return k
        return items[-1][0]

    def maybe_open_weights(self, lab):
        if lab.open_weights:
            return
        B = self.beliefs[lab.name]
        rivals = [B.cap[l.name].mu for l in self.live_labs() if l.name in B.cap]
        rank = sum(1 for r in rivals if r > lab.C) + 1
        behind = max(rivals, default=lab.C) - lab.C
        bias = self.roles[lab.role]["open_bias"]
        # A lab that believes it cannot win the lead gives weights away to win
        # users, investors and government favour instead.
        val = bias + 0.25 * behind - 0.15 * lab.revenue
        if val > 1.5 and self.u("open", self.t, lab.name) < 0.3:
            lab.open_weights = True
            self.log("open_weights", lab=lab.name, rank=rank)
            self.signals.append(Signal(self.t, "open", lab.name, lab.deployed_C))

    # ---- 8. compute market: chips are scarce; price clears
    def compute_market(self):
        c = self.cfg
        supply = c["chip_supply0"] * (1 + c["chip_supply_growth"]) ** self.t
        orders = {}
        for l in self.live_labs():
            build = self.templates[l.template][0]
            spend = build * max(0.0, l.cash) * 0.5
            if l.bloc == "B" and self.export_controls:
                spend *= 0.6        # some money cannot buy frontier chips
            orders[l.name] = spend
        total_spend = sum(orders.values())
        base_cost = c["chip_price0"] * supply
        self.chip_price = c["chip_price0"] * max(1.0, total_spend / max(1e-6, base_cost)) ** 0.7
        for l in self.live_labs():
            spend = orders[l.name]
            units = spend / self.chip_price
            if l.bloc == "B" and self.export_controls:
                units *= 0.7        # worse chips per dollar
            l.cash -= spend
            l.capex = spend
            if units > 0:
                l.pipeline.append((self.t + c["compute_lag"], units))

    # ---- 9. capital market: investors fund perceived momentum
    def capital_market(self):
        c = self.cfg
        labs = self.live_labs()
        if not labs:
            return
        obs = {}
        for l in labs:
            recent = [v for (_, v) in self.bench_hist[l.name][-4:]]
            if len(recent) >= 2:
                obs[l.name] = (recent[-1], recent[-1] - recent[0])
            else:
                obs[l.name] = (l.deployed_C, 0.3)
        top = max(v[0] for v in obs.values())
        pool = c["investor_base"] * self.sentiment * (1 + 0.05 * self.t)
        vals = {}
        for l in labs:
            lvl, mom = obs[l.name]
            v = (max(0.1, lvl) / max(1e-6, top)) ** 2 * math.exp(0.5 * max(-1.0, min(4.0, mom)))
            if l.open_weights:
                v *= 1.15
            if l.bloc == "B":
                v *= c["bloc_b_market_access"]
            vals[l.name] = v
        z = sum(vals.values())
        for l in labs:
            r = pool * vals[l.name] / z
            l.cash += r
            l.raised = r
            l.raised_ema = 0.6 * l.raised_ema + 0.4 * r
            l.cash += l.ext
            sub = self.gov_policy[l.bloc]["subsidy"]
            if sub > 0:
                l.cash += sub * (1.2 if l.role == "state" else 0.5)

    # ---- 10. R&D: training, safety, spillover, diffusion
    def train_gain(self, lab, train_K, believed=False):
        c = self.cfg
        if train_K <= 0:
            return 0.0
        base = c["train_k"] * train_K ** self.unk["scaling"] if not believed else \
            c["train_k"] * train_K ** 0.55
        auto = self.unk["automation"] if not believed else 0.3
        boost = 1 + auto * max(0.0, lab.C / c["C_AUTO"] - 1)
        eff = self.unk.get("b_efficiency", 1.0) if (lab.bloc == "B" and not believed) else 1.0
        return base * boost * eff / max(1.0, lab.C / 15) ** 0.3

    def resolve_rnd(self):
        c = self.cfg
        labs = self.live_labs()
        for l in labs:
            build, train, safety, serve = self.templates[l.template]
            tot = train + safety + serve
            reg = self.gov_policy[l.bloc]["regulate"]
            tK = l.K * train / tot * (1 - 0.5 * reg)
            sK = l.K * safety / tot
            l.train_frac = train / tot
            l._serveK = l.K * serve / tot
            l._serve_share = serve / tot
            l.C += self.train_gain(l, tK)
            l.safety_gain = c["safety_k"] * math.sqrt(max(0.0, sK))
            l.S += l.safety_gain
        if self.mech["spillover"] and len(labs) > 1:
            published = {l.name: l.safety_gain * self.roles[l.role]["publish_safety"] for l in labs}
            total = sum(published.values())
            for l in labs:
                others = (total - published[l.name]) / (len(labs) - 1)
                l.S += c["spill_rate"] * others
        front = self.frontier_deployed()
        open_front = max((l.deployed_C for l in labs if l.open_weights), default=0.0)
        for l in labs:
            pull = self.unk["leak"] * max(0.0, front - l.C)
            pull += 2 * self.unk["leak"] * max(0.0, open_front - l.C)
            l.C += pull
        for l in labs:
            if l._serveK > 0:
                l.deployed_C = l.C

    # ---- 11. product market
    def product_market(self):
        c = self.cfg
        labs = self.live_labs()
        front = self.frontier_deployed()
        mkt = c["market0"] * self.unk["demand"] * (front / 10.0) ** 1.3 * self.adoption()
        open_front = max((l.deployed_C for l in labs if l.open_weights), default=0.0)
        if front > 0:
            mkt *= 1 - c["commoditize"] * (open_front / front)
        attract = {l.name: l._serveK ** 0.5 * math.exp(0.35 * (l.deployed_C - front)) * l.rep
                   for l in labs}
        z = sum(attract.values()) or 1.0
        total = 0.0
        for l in labs:
            r = min(mkt * attract[l.name] / z, l._serveK * c["serve_cap"])
            if l.open_weights:
                r *= 0.6
            l.revenue = r
            l.cash += r
            total += r
        self.market_rev = total

    # ---- 12. incidents (truth)
    def incidents(self):
        c = self.cfg
        for l in self.live_labs():
            gap = max(0.0, l.C - l.S)
            exposure = 0.3 * l.train_frac + (l._serveK / max(1e-6, l.K))
            lam = self.unk["hazard"] * gap / 10.0 * exposure
            if self.u("incident", self.t, l.name) < 1 - math.exp(-lam):
                sev = self.expo("severity", self.t, l.name)
                detect = self.unk["detect"]
                if self.gov_policy[l.bloc]["disclosure"]:
                    detect = max(detect, c["disclosed_detect"])
                public = self.u("publicity", self.t, l.name) < detect
                self.pending_incidents.append(dict(lab=l.name, sev=sev, public=public))
                self.log("incident", lab=l.name, bloc=l.bloc, sev=round(sev, 2), public=public)
                l.rep *= 0.9 if public else 0.98
                l.cash -= 0.3 * sev
                p_cat = c["incident_catastrophe"] * sev * (l.C / c["C_STAR"]) ** 3
                if not self.outcome and self.u("incident_cat", self.t, l.name) < p_cat:
                    self.outcome = dict(kind="catastrophe_incident", t=self.t, winner=l.name, bloc=l.bloc)
                    self.log("catastrophe", lab=l.name)
                if public:
                    self.sentiment *= 0.95

    # ---- 13. public opinion and physical disruption
    def public_opinion(self):
        c = self.cfg
        sens = self.unk["sensitivity"]
        disp = c["displacement"] * self.adoption() * self.frontier_deployed() / 10.0
        now = [e for e in self.events if e["kind"] == "incident" and e["t"] == self.t and e["public"]]
        for b in self.public:
            n_local = sum(1 for i in now if i["bloc"] == b)
            n_global = len(now)
            self.public[b] += sens * (0.5 * n_local + 0.15 * n_global + disp)
            self.public[b] *= (1 - c["public_decay"])
            mult = self.govs_conf[b]["protest_mult"]
            excess = self.public[b] - c["protest_threshold"]
            if excess > 0 and self.u("protest", self.t, b) < min(0.8, 0.3 * excess * mult):
                targets = sorted((l for l in self.live_labs() if l.bloc == b), key=lambda l: l.name)
                if targets:
                    l = targets[int(self.u("protest_target", self.t, b) * len(targets))]
                    lost = l.K * c["protest_damage"]
                    l.K -= lost
                    self.log("disruption", bloc=b, lab=l.name, lost=round(lost, 2))

    # ---- 14. accounting and investor sentiment
    def accounting(self):
        c = self.cfg
        for l in self.live_labs():
            # Worn-out compute is retired before upkeep is paid; distressed
            # sales and acquisitions below see only what is still installed.
            l.K *= 1.0 - self.depreciation_rate()
            l.cash -= c["upkeep"] * l.K
            if l.cash < 0 and l.K > 2.0:
                # Distressed selling: shed compute at a discount before default.
                units = min(l.K - 2.0, 0.25 * l.K, -l.cash / c["fire_sale_price"])
                l.K -= units
                l.cash += units * c["fire_sale_price"]
                l.distress_q += 1
                self.log("distress_sale", lab=l.name, units=round(units, 3))
            elif l.cash >= 0:
                l.distress_q = 0
            # Default: deeply negative cash, or a year of distressed selling.
            if l.cash < -2.0 or l.distress_q >= 4:
                l.alive = False
                self.log("bankrupt", lab=l.name)
                price = 0.1 * l.K
                buyers = [x for x in self.live_labs()
                          if x.name != l.name and x.bloc == l.bloc and x.cash > price]
                if buyers:
                    acq = max(buyers, key=lambda x: x.cash)
                    acq.K += 0.5 * l.K
                    acq.cash -= price
                    self.log("acquired", lab=l.name, by=acq.name, price=round(price, 3))
        self.prune_pact()
        prev = self.last_market_rev
        if prev > 0.05:
            growth = self.market_rev / prev - 1
            surprise = growth - self.expected_rev_growth
            self.sentiment *= math.exp(c["sentiment_eta"] * max(-0.5, min(0.5, surprise)))
        hype = 0.0
        for l in self.live_labs():
            h = self.bench_hist[l.name][-4:]
            if len(h) >= 2:
                hype += max(0.0, (h[-1][1] - h[0][1]) / (len(h) - 1))
        self.expected_rev_growth = 0.7 * self.expected_rev_growth + 0.3 * (0.03 + 0.02 * hype)
        self.sentiment = max(0.15, min(3.0, self.sentiment))
        self.last_market_rev = self.market_rev

    # ---- 15. takeoff
    def check_end(self):
        if self.outcome:
            return
        c = self.cfg
        labs = self.live_labs()
        if not labs:
            self.outcome = dict(kind="collapse", t=self.t, winner=None, bloc=None)
            return
        lead = max(labs, key=lambda l: l.C)
        if lead.C >= c["C_STAR"]:
            gap = max(0.0, lead.C - lead.S)
            p_cat = 1 - math.exp(-self.unk["hazard"] * gap / c["catastrophe_scale"])
            # One latent draw per seed, so a smaller unsafety gap at takeoff
            # can only make catastrophe less likely, whenever takeoff happens.
            if self.u("takeoff_cat") < p_cat:
                self.outcome = dict(kind="catastrophe_takeoff", t=self.t, winner=lead.name, bloc=lead.bloc)
            else:
                second = max((l.C for l in labs if l.name != lead.name), default=0.0)
                kind = "unipolar" if lead.C - second > 4 else "multipolar"
                self.outcome = dict(kind=kind, t=self.t, winner=lead.name, bloc=lead.bloc)
            self.log("takeoff", result=self.outcome["kind"], winner=self.outcome["winner"])

    def snapshot(self):
        labs = self.labs.values()
        self.history.append(dict(
            t=self.t,
            C={l.name: round(l.C, 3) for l in labs},
            S={l.name: round(l.S, 3) for l in labs},
            K={l.name: round(l.K, 3) for l in labs},
            cash={l.name: round(l.cash, 3) for l in labs},
            deployed={l.name: round(l.deployed_C, 3) for l in labs},
            bloc={l.name: l.bloc for l in labs},
            alive={l.name: l.alive for l in labs},
            template={l.name: l.template for l in labs},
            revenue=round(sum(l.revenue for l in self.live_labs()), 4),
            capex=round(sum(l.capex for l in self.live_labs()), 4),
            raised=round(sum(l.raised for l in self.live_labs()), 4),
            sentiment=round(self.sentiment, 4),
            chip_price=round(self.chip_price, 4),
            public=dict(self.public),
            pact=sorted(self.pact["members"]) if self.pact else [],
            regulate={b: p["regulate"] for b, p in self.gov_policy.items()},
            subsidy={b: p["subsidy"] for b, p in self.gov_policy.items()},
            disclosure={b: p["disclosure"] for b, p in self.gov_policy.items()},
            hazard_belief={n: round(B.hazard.mean(), 4) for n, B in self.beliefs.items()},
        ))
