"""Minimal AI-race simulation core, version 3.

No language model makes decisions. Every actor holds beliefs, receives noisy
observations of what actually happened, internalizes some of that evidence
through a role-specific filter, and chooses actions by scoring options under
its own beliefs (softmax with inertia, so randomness and habit both matter).

Three layers are kept separate on purpose:
    truth      -> what actually happened (World.labs, World.unk, incidents)
    observed   -> Signal records that an observer actually received
    believed   -> Beliefs objects, updated through receptivity/attention filters

Version 2 changes (see FINDINGS.md for why):
- Keyed random draws: every draw is a hash of (seed, purpose, quarter, actor),
  so a variant that changes one thing does not reshuffle unrelated luck.
- Each role has its own model of the world (what it assumes about rivals'
  safety) and its own motivated-reasoning discount for its own incidents.
- Labs weigh their funding outlook when choosing, so investor sentiment can
  change behaviour.
- Optional mechanisms, each switchable in cfg["mech"]: funding_in_decisions,
  role_world_models, motivated, spillover, disclosure, theft, sabotage,
  consolidation. Government triggers depend on beliefs, not schedules.
- Fixes: pact cheating counted once; investors read per-lab benchmark history.

Version 3 change:
- Installed compute depreciates (cfg["depreciation"], 5% per quarter, about a
  five-year chip life), switchable as cfg["mech"]["depreciation"]. Labs plan
  with it: compute they hold or order is worth less the longer they wait to
  use it. With the switch off, version 3 reproduces version 2 exactly.

Hidden "unknown prevalence" constants are drawn per seed. Nobody, including
the actors, knows them.

Variants extend this by subclassing World and overriding hook methods, and/or
by returning a modified config from make_config(base). Do not edit this file
from a variant; see variants/README.md.

Units are synthetic game units (cash ~ $B, capability ~ arbitrary index with
takeoff at C_STAR). They are not calibrated estimates.
"""
