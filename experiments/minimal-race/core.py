class GridBelief:
    """Belief over a scalar on a fixed grid. Updates use tempered likelihoods:
    posterior ∝ prior * likelihood**receptivity. That exponent is the filter
    between what was observed and what is internalized."""

    def __init__(self, lo, hi, n, prior_frac, concentration=4.0):
        self.xs = [lo + (hi - lo) * i / (n - 1) for i in range(n)]
        a = 1 + concentration * prior_frac
        b = 1 + concentration * (1 - prior_frac)
        ps = []
        for i in range(n):
            u = (i + 0.5) / n
            ps.append(u ** (a - 1) * (1 - u) ** (b - 1))
        z = sum(ps)
        self.ps = [p / z for p in ps]

    def update(self, loglik_fn, receptivity):
        if receptivity <= 0:
            return
        logs = [math.log(max(p, 1e-300)) + receptivity * loglik_fn(x)
                for p, x in zip(self.ps, self.xs)]
        m = max(logs)
        ws = [math.exp(l - m) for l in logs]
        z = sum(ws)
        self.ps = [w / z for w in ws]

    def mean(self):
        return sum(p * x for p, x in zip(self.ps, self.xs))

    def sd(self):
        mu = self.mean()
        return math.sqrt(max(0.0, sum(p * (x - mu) ** 2 for p, x in zip(self.ps, self.xs))))


@dataclass
class GaussEst:
    """Estimate of a lab's capability. Kalman-style update with an attention
    filter: small surprises are partly ignored."""
    mu: float
    var: float
    growth: float = 0.3

    def predict(self):
        self.mu += self.growth
        self.var += 0.5

    def observe(self, y, noise_var, attention):
        innov = y - self.mu
        sd = math.sqrt(self.var + noise_var)
        gain = self.var / (self.var + noise_var)
        if abs(innov) < attention * sd:
            gain *= 0.3          # habituation: unsurprising news barely moves you
        self.mu += gain * innov
        self.var *= (1 - gain)
        self.growth = 0.8 * self.growth + 0.2 * max(0.0, gain * innov + self.growth)


class Beliefs:
    def __init__(self, owner, labs, cfg, hazard_prior, demand_prior, receptivity,
                 attention, start_C, rival_safety, self_discount=0.0):
        n = cfg["grid"]
        self.owner = owner
        self.receptivity = receptivity
        self.attention = attention
        self.rival_safety = rival_safety
        self.self_discount = self_discount
        hz = cfg["unknowns"]["hazard"]
        dm = cfg["unknowns"]["demand"]
        self.hazard = GridBelief(hz[0], hz[1], n, hazard_prior)
        self.hazard_prior_mean = self.hazard.mean()
        self.demand = GridBelief(dm[0], dm[1], n, demand_prior)
        # Governments estimate every lab, including their own bloc's.
        self.cap = {a: GaussEst(start_C[a], 4.0) for a in labs if a != owner}
        # Beta belief that pact partners defect.
        self.defect_a, self.defect_b = 1.0, 2.0
        self.incidents_seen = 0

    def p_defect(self):
        return self.defect_a / (self.defect_a + self.defect_b)


